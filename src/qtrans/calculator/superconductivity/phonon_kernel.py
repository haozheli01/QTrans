"""Phonon kernels and FFT-backed positive-frequency matrix products."""

from collections import defaultdict

import numpy as np


def _trapezoid_weights(grid):
    weights = np.empty_like(grid)
    weights[0] = 0.5 * (grid[1] - grid[0])
    weights[-1] = 0.5 * (grid[-1] - grid[-2])
    if grid.size > 2:
        weights[1:-1] = 0.5 * (grid[2:] - grid[:-2])
    return weights


def _toeplitz_matvec(first_column, first_row, vector):
    size = vector.size
    if first_column.shape != (size,) or first_row.shape != (size,):
        raise ValueError("Toeplitz vectors must have the same length as the input.")
    embedding = np.concatenate((first_column, np.zeros(1), first_row[:0:-1]))
    padded = np.concatenate((vector, np.zeros(size)))
    result = np.fft.irfft(
        np.fft.rfft(embedding) * np.fft.rfft(padded), n=2 * size
    )
    return result[:size]


def apply_lag_kernel(lag_values, vector, operation):
    """Apply lambda(|n-m|) +/- lambda(n+m+1) to a positive grid."""
    vector = np.asarray(vector, dtype=float)
    size = vector.size
    if lag_values.size < 2 * size:
        raise ValueError("The lag kernel does not cover all Matsubara sums.")
    toeplitz = _toeplitz_matvec(
        lag_values[:size], lag_values[:size], vector
    )
    hankel_values = lag_values[1:2 * size]
    hankel = _toeplitz_matvec(
        hankel_values[size - 1:], hankel_values[size - 1::-1], vector[::-1]
    )
    if operation == "sum":
        return toeplitz + hankel
    if operation == "difference":
        return toeplitz - hankel
    raise ValueError("operation must be 'sum' or 'difference'.")


class IsotropicPhononKernel:
    """Kernel generated by a sampled isotropic alpha^2 F spectrum."""

    def __init__(self, phonon_frequencies, alpha2f):
        self.frequencies = np.asarray(phonon_frequencies, dtype=float)
        self.alpha2f = np.asarray(alpha2f, dtype=float)
        self.integration_weights = _trapezoid_weights(self.frequencies)
        self._cache = {}

    def lag_values(self, temperature, number_of_frequencies):
        key = (float(temperature), int(number_of_frequencies))
        cached = self._cache.get(key)
        if cached is not None:
            return cached
        transfers = 2.0 * np.pi * temperature * np.arange(
            2 * number_of_frequencies, dtype=float
        )
        numerator = (
            2.0 * self.integration_weights * self.frequencies * self.alpha2f
        )
        values = np.empty_like(transfers)
        chunk_size = 256
        squared_frequencies = self.frequencies ** 2
        for start in range(0, transfers.size, chunk_size):
            stop = min(start + chunk_size, transfers.size)
            denominator = (
                squared_frequencies[None, :]
                + transfers[start:stop, None] ** 2
            )
            values[start:stop] = np.sum(numerator[None, :] / denominator, axis=1)
        self._cache = {key: values}
        return values

    def apply(self, vector, temperature, operation):
        vector = np.asarray(vector, dtype=float)
        lags = self.lag_values(temperature, vector.size)
        return apply_lag_kernel(lags, vector, operation)


class TransitionPhononKernel:
    """Reference sparse state-resolved kernel grouped by directed state pairs."""

    def __init__(self, transitions, maximum_cache_bytes=1.5 * 1024 ** 3):
        self.transitions = transitions
        self.maximum_cache_bytes = float(maximum_cache_bytes)
        groups = defaultdict(list)
        for index, pair in enumerate(zip(
            transitions.source_state, transitions.target_state
        )):
            groups[(int(pair[0]), int(pair[1]))].append(index)
        self.groups = {
            pair: np.asarray(indices, dtype=np.int64)
            for pair, indices in groups.items()
        }
        self._cache = {}

    def _lag_cache(self, temperature, number_of_frequencies):
        key = (float(temperature), int(number_of_frequencies))
        cached = self._cache.get(key)
        if cached is not None:
            return cached
        element_count = len(self.groups) * 2 * number_of_frequencies
        required_bytes = element_count * np.dtype(float).itemsize
        if required_bytes > self.maximum_cache_bytes:
            raise MemoryError(
                "The state-resolved Matsubara kernel requires approximately "
                "{:.2f} GiB, above the {:.2f} GiB safety limit. Reduce the "
                "state set/cutoff or implement the production C/MPI kernel."
                .format(required_bytes / 1024 ** 3,
                        self.maximum_cache_bytes / 1024 ** 3)
            )
        transfers = 2.0 * np.pi * temperature * np.arange(
            2 * number_of_frequencies, dtype=float
        )
        cache = {}
        for pair, indices in self.groups.items():
            frequencies = self.transitions.phonon_frequency[indices]
            couplings = self.transitions.coupling_weight[indices]
            numerator = 2.0 * couplings * frequencies
            values = np.sum(
                numerator[None, :]
                / (frequencies[None, :] ** 2 + transfers[:, None] ** 2),
                axis=1,
            )
            cache[pair] = values
        self._cache = {key: cache}
        return cache

    def apply(self, vectors, temperature, operation):
        vectors = np.asarray(vectors, dtype=float)
        if vectors.ndim != 2:
            raise ValueError("State-resolved kernel input must have shape (state, nfreq).")
        number_of_states, number_of_frequencies = vectors.shape
        if number_of_states != self.transitions.number_of_states:
            raise ValueError("Kernel input has the wrong number of electronic states.")
        output = np.zeros_like(vectors)
        lag_cache = self._lag_cache(temperature, number_of_frequencies)
        for (source, target), lags in lag_cache.items():
            output[source] += apply_lag_kernel(
                lags, vectors[target], operation
            )
        return output
